-- ARCADE Milano - V9 (team BAD): nuovo espositore da Power Apps
--
-- PERCHE'
--   Il back-office deve poter creare un espositore (pulsante "Nuovo
--   espositore", B-44). Due ostacoli:
--   1. core.exhibitor e core.exhibitor_contact hanno la chiave
--      GENERATED ALWAYS: Power Apps non riesce a inserire (stesso limite
--      del connettore risolto dalla V8 per altre 8 tabelle).
--   2. core.exhibitor.legal_name_norm e' NOT NULL e va calcolata con la
--      stessa regola del caricatore V6 (dq.norm_company), altrimenti la
--      ricerca per nome e gli alias non sono coerenti.
--
-- COSA FA
--   1. Chiavi di exhibitor ed exhibitor_contact: GENERATED BY DEFAULT +
--      trigger core.assign_identity_if_zero della V8 (chiave 0 o vuota ->
--      numero dalla sequenza). Chi non passa la chiave non cambia nulla.
--   2. Trigger BEFORE INSERT/UPDATE su core.exhibitor: se legal_name_norm
--      arriva vuota (Power Apps manda ""), la calcola con
--      dq.norm_company(legal_name). In UPDATE la ricalcola se cambia la
--      ragione sociale e il valore normalizzato non e' stato toccato.
--      Un valore passato esplicitamente (caricatore V6) resta com'e'.
--
-- PREREQUISITI: V8 (core.assign_identity_if_zero) e V6 (dq.norm_company).
-- NON CAMBIA: nessuna tabella, colonna, vincolo o dato.
-- SOLO CARATTERI ASCII.
--
-- PER TORNARE INDIETRO:
--   DROP TRIGGER trg_exhibitor_name_norm ON core.exhibitor;
--   DROP FUNCTION core.fill_exhibitor_name_norm();
--   DROP TRIGGER trg_assign_id ON core.exhibitor;
--   DROP TRIGGER trg_assign_id ON core.exhibitor_contact;
--   ALTER TABLE core.exhibitor ALTER COLUMN exhibitor_id SET GENERATED ALWAYS;
--   ALTER TABLE core.exhibitor_contact ALTER COLUMN contact_id SET GENERATED ALWAYS;
-- =====================================================================

BEGIN;

-- 1. Chiavi compatibili con Power Apps (come V8)
ALTER TABLE core.exhibitor ALTER COLUMN exhibitor_id SET GENERATED BY DEFAULT;
DROP TRIGGER IF EXISTS trg_assign_id ON core.exhibitor;
CREATE TRIGGER trg_assign_id BEFORE INSERT ON core.exhibitor
    FOR EACH ROW EXECUTE FUNCTION core.assign_identity_if_zero('exhibitor_id');

ALTER TABLE core.exhibitor_contact ALTER COLUMN contact_id SET GENERATED BY DEFAULT;
DROP TRIGGER IF EXISTS trg_assign_id ON core.exhibitor_contact;
CREATE TRIGGER trg_assign_id BEFORE INSERT ON core.exhibitor_contact
    FOR EACH ROW EXECUTE FUNCTION core.assign_identity_if_zero('contact_id');

-- 2. Nome normalizzato calcolato dal DB con la regola della V6
CREATE OR REPLACE FUNCTION core.fill_exhibitor_name_norm()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, pg_temp
AS $$
BEGIN
    IF NEW.legal_name_norm IS NULL OR btrim(NEW.legal_name_norm) = '' THEN
        NEW.legal_name_norm := dq.norm_company(NEW.legal_name);
    ELSIF TG_OP = 'UPDATE'
          AND NEW.legal_name IS DISTINCT FROM OLD.legal_name
          AND NEW.legal_name_norm = OLD.legal_name_norm THEN
        NEW.legal_name_norm := dq.norm_company(NEW.legal_name);
    END IF;
    RETURN NEW;
END
$$;

REVOKE ALL ON FUNCTION core.fill_exhibitor_name_norm() FROM PUBLIC;

DROP TRIGGER IF EXISTS trg_exhibitor_name_norm ON core.exhibitor;
CREATE TRIGGER trg_exhibitor_name_norm BEFORE INSERT OR UPDATE ON core.exhibitor
    FOR EACH ROW EXECUTE FUNCTION core.fill_exhibitor_name_norm();

COMMIT;
