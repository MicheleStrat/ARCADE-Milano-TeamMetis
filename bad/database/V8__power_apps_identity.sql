-- =====================================================================
-- ARCADE Milano - V8 (team BAD): chiavi automatiche compatibili con Power Apps
--
-- PERCHE'
--   Il connettore PostgreSQL di Power Apps / Power Automate, in "Insert row"
--   (e quindi in Patch), pretende un valore esplicito per la chiave primaria,
--   anche se la colonna ha un valore automatico (limite documentato da
--   Microsoft). Con GENERATED ALWAYS AS IDENTITY PostgreSQL rifiuta qualsiasi
--   valore esplicito: Power Apps non riesce a creare righe.
--   Prova dell'11/11 su metiserver2: Patch su core.quote -> "Il campo
--   'quote_id' e' obbligatorio".
--
-- COSA FA
--   1. Le chiavi delle 8 tabelle in cui le app BAD creano righe passano da
--      GENERATED ALWAYS a GENERATED BY DEFAULT (stessa sequenza, stessi
--      numeri, nessun dato toccato).
--   2. Un trigger BEFORE INSERT assegna il numero dalla sequenza SOLO se la
--      chiave arriva vuota o <= 0. Power Apps manda sempre 0.
--      Chi non passa la chiave (backend del BID, caricatori V5/V6/V7) riceve
--      il valore di default come prima: il trigger non lo cambia e non
--      consuma numeri in piu'.
--   Prova con tabella usa e getta su metiserver2 (11/11): Patch con id 0,
--   tre inserimenti, id 1, 2, 3 restituiti correttamente all'app.
--
-- REGOLA PER LE APP
--   Nei Patch di creazione la chiave si passa SEMPRE a 0. Mai un numero
--   scelto dall'app: un valore positivo verrebbe usato cosi' com'e'.
--
-- NON CAMBIA
--   Nessuna tabella nuova, nessuna colonna, nessun vincolo, nessun dato.
--   preemption e stand_edition restano GENERATED ALWAYS (le app le
--   aggiornano soltanto).
--
-- SOLO CARATTERI ASCII (vedi note sulla codifica dei file eseguiti da Windows).
--
-- PER TORNARE INDIETRO (stessa lista di tabelle):
--   DROP TRIGGER trg_assign_id ON core.<tabella>;
--   ALTER TABLE core.<tabella> ALTER COLUMN <chiave> SET GENERATED ALWAYS;
--   DROP FUNCTION core.assign_identity_if_zero();
-- =====================================================================

BEGIN;

-- Assegna la chiave dalla sequenza dell'identity quando arriva NULL o <= 0.
-- TG_ARGV[0] = nome della colonna chiave.
-- SECURITY DEFINER: nextval() viene eseguito con i permessi del proprietario
-- delle tabelle, quindi arcade_app non ha bisogno di permessi sulle sequenze.
CREATE OR REPLACE FUNCTION core.assign_identity_if_zero()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, pg_temp
AS $$
DECLARE
    v_col  text   := TG_ARGV[0];
    v_cur  bigint := (to_jsonb(NEW) ->> TG_ARGV[0])::bigint;
    v_seq  text;
BEGIN
    IF v_cur IS NULL OR v_cur <= 0 THEN
        v_seq := pg_get_serial_sequence(format('%I.%I', TG_TABLE_SCHEMA, TG_TABLE_NAME), v_col);
        IF v_seq IS NULL THEN
            RAISE EXCEPTION 'assign_identity_if_zero: nessuna sequenza per %.%.%',
                TG_TABLE_SCHEMA, TG_TABLE_NAME, v_col;
        END IF;
        NEW := jsonb_populate_record(NEW, jsonb_build_object(v_col, nextval(v_seq)));
    END IF;
    RETURN NEW;
END
$$;

REVOKE ALL ON FUNCTION core.assign_identity_if_zero() FROM PUBLIC;

DO $$
DECLARE
    r record;
BEGIN
    FOR r IN
        SELECT * FROM (VALUES
            ('quote',          'quote_id'),
            ('quote_line',     'quote_line_id'),
            ('contract',       'contract_id'),
            ('contract_stand', 'contract_stand_id'),
            ('contract_line',  'contract_line_id'),
            ('payment',        'payment_id'),
            ('sponsorship',    'sponsorship_id'),
            ('gate_reading',   'reading_id')
        ) AS t(tbl, col)
    LOOP
        EXECUTE format('ALTER TABLE core.%I ALTER COLUMN %I SET GENERATED BY DEFAULT', r.tbl, r.col);
        EXECUTE format('DROP TRIGGER IF EXISTS trg_assign_id ON core.%I', r.tbl);
        EXECUTE format(
            'CREATE TRIGGER trg_assign_id BEFORE INSERT ON core.%I '
            'FOR EACH ROW EXECUTE FUNCTION core.assign_identity_if_zero(%L)',
            r.tbl, r.col);
    END LOOP;
END
$$;

COMMIT;
