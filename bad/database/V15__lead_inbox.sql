BEGIN;

CREATE SCHEMA IF NOT EXISTS flow;

-- ---------------------------------------------------------------------
-- 1. Sale (solo per il proprietario e le funzioni SECURITY DEFINER)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS flow.app_secret (
    name  text PRIMARY KEY,
    value text NOT NULL CHECK (length(value) >= 16)
);
REVOKE ALL ON flow.app_secret FROM PUBLIC;
COMMENT ON TABLE flow.app_secret IS
 'Segreti lato server (sale dei contatti). Nessun ruolo applicativo deve avere permessi qui.';

-- Hash dell'email con la stessa regola della V7: sha256(sale || email minuscola senza spazi).
-- Non e' concessa a nessun ruolo applicativo.
CREATE OR REPLACE FUNCTION flow.lead_email_hash(p_email text)
RETURNS bytea
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, pg_temp
AS $$
DECLARE
    v_sale text;
BEGIN
    SELECT value INTO v_sale FROM flow.app_secret WHERE name = 'ARCADE_SALE';
    IF v_sale IS NULL THEN
        RAISE EXCEPTION 'Sale non configurato sul server (flow.app_secret)';
    END IF;
    RETURN sha256(convert_to(v_sale || lower(btrim(p_email)), 'UTF8'));
END
$$;
REVOKE ALL ON FUNCTION flow.lead_email_hash(text) FROM PUBLIC;

-- ---------------------------------------------------------------------
-- 2. Sorgente dei contatti dal modulo
-- ---------------------------------------------------------------------
INSERT INTO core.data_source (code, description, kind, source_timezone, is_demo)
SELECT 'BAD_MODULO_QR', 'Contatti dal modulo Forms dei QR agli stand (B-25, B-72)', 'MANUAL', 'Europe/Rome', true
WHERE NOT EXISTS (SELECT 1 FROM core.data_source WHERE code = 'BAD_MODULO_QR');

-- ---------------------------------------------------------------------
-- 3. Tabella di ingresso
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS flow.lead_inbox (
    inbox_id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    form_response_id text        NOT NULL UNIQUE,      -- id della risposta Forms: niente doppioni se il flusso ritenta
    submitted_at     timestamptz NOT NULL,             -- ora di invio della risposta
    stand_code       text        NOT NULL,             -- es. P1-A08 (dal link del QR)
    email            text,                             -- arriva dal flusso, il trigger la svuota SEMPRE
    age_band         text        NOT NULL,             -- codice di core.age_band (14-17, 18-24, ..., famiglia)
    interest         text        NOT NULL,             -- codice di core.lead_interest
    consent          boolean     NOT NULL,             -- Si = true, No = false
    esito            text CHECK (esito IN ('OK', 'DUPLICATE')),
    lead_code        text,                             -- contatto creato (o quello gia' esistente se DUPLICATE)
    processed_at     timestamptz,
    CHECK (email IS NULL)                              -- garanzia: l'email in chiaro non resta mai nella tabella
);
COMMENT ON TABLE flow.lead_inbox IS
 'Ingresso dei contatti dal modulo QR (flusso Power Automate). Il trigger calcola l''hash, scrive in core.stand_lead e svuota l''email.';

-- Chiave compatibile con il connettore (chiave 0 -> numero dalla sequenza), come la V8.
DROP TRIGGER IF EXISTS trg_assign_id ON flow.lead_inbox;
CREATE TRIGGER trg_assign_id BEFORE INSERT ON flow.lead_inbox
    FOR EACH ROW EXECUTE FUNCTION core.assign_identity_if_zero('inbox_id');

-- ---------------------------------------------------------------------
-- 4. Elaborazione (parte dopo trg_assign_id: i trigger BEFORE vanno in ordine alfabetico)
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION flow.process_lead_inbox()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, pg_temp
AS $$
DECLARE
    v_email      text := lower(btrim(coalesce(NEW.email, '')));
    v_stand      text := upper(btrim(NEW.stand_code));
    v_se_id      integer;
    v_year       smallint;
    v_exh_id     integer;
    v_band_id    smallint;
    v_band_code  text;
    v_band_minor boolean;
    v_int_id     smallint;
    v_hash       bytea;
    v_source     smallint;
    v_prefix     text;
    v_next       integer;
    v_existing   text;
BEGIN
    -- email
    IF v_email !~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$' THEN
        RAISE EXCEPTION 'Contatto stand %: email non valida', v_stand;
    END IF;

    -- stand nell'edizione in vendita o in corso (la piu'' recente)
    SELECT se.stand_edition_id, e.year
      INTO v_se_id, v_year
      FROM core.stand s
      JOIN core.stand_edition se ON se.stand_id = s.stand_id
      JOIN core.edition e        ON e.edition_id = se.edition_id
     WHERE s.stand_code = v_stand
       AND e.status IN ('SALES_OPEN', 'RUNNING')
     ORDER BY e.year DESC
     LIMIT 1;
    IF v_se_id IS NULL THEN
        RAISE EXCEPTION 'Contatto stand %: stand inesistente o edizione non aperta', v_stand;
    END IF;

    -- espositore del contratto firmato attivo su quello stand
    SELECT c.exhibitor_id
      INTO v_exh_id
      FROM core.contract_stand cs
      JOIN core.contract c ON c.contract_id = cs.contract_id
     WHERE cs.stand_edition_id = v_se_id
       AND cs.released_at IS NULL
       AND c.status = 'SIGNED'
     LIMIT 1;
    IF v_exh_id IS NULL THEN
        RAISE EXCEPTION 'Contatto stand %: stand non venduto (nessun contratto firmato)', v_stand;
    END IF;

    -- fascia d'eta'
    SELECT age_band_id, code, is_minor
      INTO v_band_id, v_band_code, v_band_minor
      FROM core.age_band
     WHERE code = btrim(NEW.age_band);
    IF v_band_id IS NULL THEN
        RAISE EXCEPTION 'Contatto stand %: fascia d''eta'' sconosciuta (%)', v_stand, NEW.age_band;
    END IF;
    IF v_band_minor AND v_band_code <> '14-17' THEN
        RAISE EXCEPTION 'Contatto stand %: fascia % non ammessa nel modulo', v_stand, v_band_code;
    END IF;

    -- interesse
    SELECT interest_id INTO v_int_id FROM core.lead_interest WHERE code = btrim(NEW.interest);
    IF v_int_id IS NULL THEN
        RAISE EXCEPTION 'Contatto stand %: interesse sconosciuto (%)', v_stand, NEW.interest;
    END IF;

    v_hash := flow.lead_email_hash(v_email);

    -- un solo contatto per email e stand (B-73): niente errore, la riga resta come DUPLICATE
    PERFORM pg_advisory_xact_lock(hashtext('flow.lead_inbox'));
    SELECT lead_code INTO v_existing
      FROM core.stand_lead
     WHERE stand_edition_id = v_se_id AND email_hash = v_hash
     LIMIT 1;

    NEW.stand_code   := v_stand;
    NEW.age_band     := v_band_code;
    NEW.interest     := btrim(NEW.interest);
    NEW.email        := NULL;                 -- l'email in chiaro non resta mai
    NEW.processed_at := now();

    IF v_existing IS NOT NULL THEN
        NEW.esito     := 'DUPLICATE';
        NEW.lead_code := v_existing;
        RETURN NEW;
    END IF;

    SELECT source_id INTO v_source FROM core.data_source WHERE code = 'BAD_MODULO_QR';

    v_prefix := 'L' || right(v_year::text, 2);
    SELECT coalesce(max(substr(lead_code, 4)::integer), 0) + 1
      INTO v_next
      FROM core.stand_lead
     WHERE lead_code ~ ('^' || v_prefix || '[0-9]{5}$');

    INSERT INTO core.stand_lead (lead_code, stand_edition_id, exhibitor_id, captured_at, email_hash,
                                 age_band_id, province_id, interest_id, marketing_consent,
                                 is_qualified, review_status, source_id)
    VALUES (v_prefix || lpad(v_next::text, 5, '0'), v_se_id, v_exh_id, NEW.submitted_at, v_hash,
            v_band_id, NULL, v_int_id, NEW.consent,
            false, CASE WHEN v_band_code = '14-17' THEN 'PRIVACY_REVIEW' ELSE 'OK' END, v_source);

    NEW.esito     := 'OK';
    NEW.lead_code := v_prefix || lpad(v_next::text, 5, '0');
    RETURN NEW;
END
$$;
REVOKE ALL ON FUNCTION flow.process_lead_inbox() FROM PUBLIC;

DROP TRIGGER IF EXISTS trg_lead_inbox_process ON flow.lead_inbox;
CREATE TRIGGER trg_lead_inbox_process BEFORE INSERT ON flow.lead_inbox
    FOR EACH ROW EXECUTE FUNCTION flow.process_lead_inbox();

