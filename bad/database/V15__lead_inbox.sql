-- ARCADE Milano - V15 (team BAD): contatti dal modulo QR degli stand
--
-- PERCHE' (B-25, B-27, B-72, B-73)
--   Il visitatore inquadra il QR dello stand, compila il modulo Forms e
--   un flusso Power Automate (BAD-07-06, Lorenzo) deve portare il contatto
--   in core.stand_lead. Due ostacoli:
--   1. core.stand_lead vuole l'email SOLO come sha256(sale || email) e il
--      sale e' segreto: non puo' stare nel flusso. Quindi l'hash lo calcola
--      il database (B-72).
--   2. core.stand_lead ha la chiave GENERATED ALWAYS: il connettore non
--      riesce a inserire (stesso limite della V8).
--
-- COSA FA
--   1. flow.app_secret: tabella del sale. Nessun permesso a nessun ruolo
--      applicativo: la legge solo la funzione del trigger. Il sale NON e'
--      in questo file: si inserisce a parte (vedi in fondo).
--   2. flow.lead_inbox: tabella di ingresso in cui il flusso fa
--      "Inserisci riga" (chiave 0 come la V8). Un trigger BEFORE INSERT:
--        - trova lo stand nell'edizione in vendita/in corso e l'espositore
--          del contratto FIRMATO attivo; stand non venduto -> errore;
--        - fascia d'eta': 14-17 -> PRIVACY_REVIEW; 0-7 e 8-13 -> errore
--          (non sono nel modulo); famiglia e 18+ -> OK;
--        - interesse e fascia per codice (stesse etichette del DB);
--        - email in minuscolo senza spazi -> sha256(sale || email);
--        - stessa email sullo stesso stand -> NON crea un secondo contatto,
--          la riga resta con esito DUPLICATE (B-73);
--        - crea il contatto con lead_code L<aa><5 cifre> (L2600001...);
--        - SVUOTA L'EMAIL: nella tabella di ingresso non resta mai.
--      Su errore il trigger blocca l'inserimento: il flusso va in errore e
--      manda la sua mail al team (senza l'email del visitatore). In quel
--      caso nel DB non resta nulla.
--   3. Sorgente core.data_source 'BAD_MODULO_QR' (is_demo = true).
--   4. Permessi: arcade_app (ne fa parte arcade_powerapp, l'utente dei
--      flussi) INSERT e SELECT su flow.lead_inbox; niente su app_secret.
--
-- PREREQUISITI: V1-V3, V8 (core.assign_identity_if_zero), V10 (schema flow).
-- NON CAMBIA: nessuna tabella, colonna o dato del core del BID.
-- SOLO CARATTERI ASCII.
--
